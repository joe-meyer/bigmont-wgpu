//! WGSL generator for the 32-bit limb scheme (`LimbScheme::Limb32`): cooperative (several lanes per
//! number) Montgomery squaring with 32-bit limbs and u64 products. It needs `SHADER_INT64` and
//! subgroup operations, so it is never generated for the browser target (see
//! `KernelConfig::try_wgsl_for`). Ported from the experimental `coop32` kernel, which was verified
//! against the oracle on an RTX 4070 and an RX 6700 XT.
//!
//! Layout and contract match the unrolled 13-bit kernel except for the radix: `TPI` lanes share one
//! number, lane `l` holds limbs `l * LPL .. (l + 1) * LPL` as named scalars, `L = TPI * LPL` limbs
//! with `R = 2^(32 L)`, `L >= ceil((bits + 4) / 32)` (so R > 16 n). Per instance
//! `x <- x^2 R^-1 mod n`, `params.y` times, the result in [0, 2n) with every limb a full 32-bit word.
//! In [`Mode::Mul`] the multiplier limbs come from the read-only `b_limbs` (binding 4) instead of
//! `x`, giving `x <- x b R^-1 mod n`; `b` limbs are u32 words like `x`, so the chain bounds in
//! [`step`] are unchanged, and for `x, b < 4n` the result is below `16n^2 / R + n < 2n`.
//!
//! ## Carries
//!
//! 13-bit limbs absorb carries in 32-bit headroom and are normalised every 20 steps. 32-bit limbs
//! have no headroom, so every limb is carried at once inside a lane (two interleaved u64 chains per
//! step: `x * b + t + c1` and `n * m + lo + c2`, each at most 2^64 - 1) and the carry that leaves a
//! lane's last limb is not passed to the next lane; it is deferred one step:
//!
//! - The lane's last limb of a step is computed from the NEXT lane's limb 0 (fetched with one
//!   shuffle, like the 13-bit kernel). The carry out of that element has the weight of the position
//!   one above it. After the one-limb shift of the next step that position is exactly this element's
//!   own position, so the carry is added to the same element one step later, by the same lane. No
//!   carry ever crosses lanes inside the loop, and there is no ripple.
//! - Adding that deferred carry (`pend`, below 2^34) to an element that already holds
//!   `x * b + t + c` could overflow u64, so the sum is formed in two parts and the wrap is detected
//!   (`s2 < q`) and counted as 2^32 in the new `pend`.
//! - After the last step the pending carries are added into the next lane's limb 0 and rippled until
//!   no lane has one (uniform `subgroupAny` loop), like `full_normalize` in `unrolled.rs`.
//!
//! The Montgomery factor comes from lane 0's limb 0 (`bcast`), computed redundantly by every lane
//! (`m = lo(T0 + X0 * b) * ninv` with `ninv = -n^-1 mod 2^32`); the carries of that limb enter lane
//! 0's first chain element.

use crate::kernel::{KernelConfig, SUBGROUP_HELPERS};
use crate::unrolled::Mode;

/// Emits the complete native WGSL source for `cfg` (an unrolled 32-bit configuration with
/// `tpi` 4, 8, 16 or 32). Same bindings as the 13-bit unrolled kernel: `params`, `n_limbs`,
/// `ninv_buf`, `x_limbs`, plus in [`Mode::Fermat`] `e_words` and `fp` (see
/// `KernelConfig::fermat_wgsl_for`), where every squaring is followed by the conditional doubling
/// selected by the exponent bit (see [`conditional_double`]), and in [`Mode::Mul`] `b_limbs` (the
/// right operand, see `KernelConfig::try_mul_wgsl_for`).
pub(crate) fn wgsl(cfg: &KernelConfig, mode: Mode) -> Result<String, String> {
    if !matches!(cfg.tpi, 4 | 8 | 16 | 32) {
        return Err(format!(
            "the 32-bit generator supports tpi 4, 8, 16, 32 only (got {})",
            cfg.tpi
        ));
    }
    let lpl = cfg.limbs_per_lane() as usize;
    let mut g = Gen {
        lines: Vec::new(),
        depth: 0,
    };
    g.line(format!("// Generated by bigmont-core limb32.rs: TPI {}, {lpl} limbs per lane, 32-bit limbs, u64 products.", cfg.tpi));
    g.line(format!(
        "const TPI: u32 = {}u;     // lanes per number",
        cfg.tpi
    ));
    g.line(format!("const LPL: u32 = {lpl}u;     // limbs per lane"));
    g.line("const L: u32 = TPI * LPL;");
    g.line(format!("const WG: u32 = {}u;", cfg.wg));
    g.line("");
    if mode == Mode::Fermat {
        g.line("@group(0) @binding(0) var<uniform> params: vec4<u32>;          // x = instance count, y = ladder iterations in this dispatch");
    } else if mode == Mode::Mul {
        g.line("@group(0) @binding(0) var<uniform> params: vec4<u32>;          // x = instance count, y = multiplications");
    } else {
        g.line("@group(0) @binding(0) var<uniform> params: vec4<u32>;          // x = instance count, y = squarings");
    }
    g.line("@group(0) @binding(1) var<storage, read> n_limbs: array<u32>;");
    g.line("@group(0) @binding(2) var<storage, read> ninv_buf: array<u32>;   // -n^-1 mod 2^32");
    g.line("@group(0) @binding(3) var<storage, read_write> x_limbs: array<u32>;");
    if mode == Mode::Mul {
        g.line("@group(0) @binding(4) var<storage, read> b_limbs: array<u32>;   // right operand");
    }
    if mode == Mode::Fermat {
        g.line("@group(0) @binding(4) var<storage, read> e_words: array<u32>;   // n - 1, words per instance = fp.z");
        g.line("@group(0) @binding(5) var<uniform> fp: vec4<u32>;               // x = first iteration, y = nbits, z = words per instance");
    }
    g.raw(SUBGROUP_HELPERS);
    g.line("@compute @workgroup_size(WG)");
    g.line("fn main(@builtin(workgroup_id) wid: vec3<u32>, @builtin(local_invocation_index) li: u32, @builtin(subgroup_invocation_id) sg_in: u32) {");
    g.depth += 1;
    g.line("let lane = sg_in % TPI;");
    g.line("let base = sg_in - lane;");
    g.line("let inst = wid.x * (WG / TPI) + li / TPI;");
    g.line("let live = inst < params.x;");
    g.line("let ic = min(inst, params.x - 1u);     // out-of-range lanes compute on a valid instance; their store is skipped");
    g.line("let off = ic * L + lane * LPL;");
    for c in 0..lpl {
        g.line(format!("var x{c} = x_limbs[off + {c}u];"));
    }
    for c in 0..lpl {
        g.line(format!("let n{c} = n_limbs[off + {c}u];"));
    }
    if mode == Mode::Mul {
        for c in 0..lpl {
            g.line(format!("let b{c} = b_limbs[off + {c}u];"));
        }
    }
    for c in 0..lpl {
        g.line(format!("var t{c} = 0u;"));
    }
    g.line("let ninv = ninv_buf[ic];");
    g.line("let is0 = lane == 0u;");
    g.line("let N0 = bcast(n0, 0u, base);                     // lane 0's limb 0 of n");
    g.line("let NN0 = down1(n0, lane);                        // next lane's limb 0 of n (0 for the last lane)");
    g.line("for (var s = 0u; s < params.y; s++) {");
    g.depth += 1;
    g.line("let X0 = bcast(x0, 0u, base);");
    g.line("let XN0 = down1(x0, lane);");
    for c in 0..lpl {
        g.line(format!("t{c} = 0u;"));
    }
    g.line("var pend = 0lu;                                   // deferred carry into this lane's last limb (below 2^34)");
    g.line("for (var owner = 0u; owner < TPI; owner++) {");
    g.depth += 1;
    // The multiplier limbs: `x` itself when squaring, the read-only `b` when multiplying.
    let mult = if mode == Mode::Mul { "b" } else { "x" };
    for w in 0..lpl {
        step(&mut g, lpl, w, mult);
    }
    g.depth -= 1;
    g.line("}");
    resolve(&mut g, lpl);
    for c in 0..lpl {
        g.line(format!("x{c} = t{c};"));
    }
    if mode == Mode::Fermat {
        conditional_double(&mut g, lpl);
    }
    g.depth -= 1;
    g.line("}");
    g.line("if (live) {");
    g.depth += 1;
    for c in 0..lpl {
        g.line(format!("x_limbs[off + {c}u] = x{c};"));
    }
    g.depth -= 1;
    g.line("}");
    g.depth -= 1;
    g.line("}");
    Ok(g.lines.join("\n") + "\n")
}

/// Line collector with indentation.
pub(crate) struct Gen {
    pub(crate) lines: Vec<String>,
    pub(crate) depth: usize,
}

impl Gen {
    pub(crate) fn line(&mut self, s: impl AsRef<str>) {
        self.lines
            .push(format!("{}{}", "    ".repeat(self.depth), s.as_ref()));
    }
    pub(crate) fn raw(&mut self, s: &str) {
        self.lines.push(s.to_string());
    }
}

/// Fermat mode: `x <- 2x` when exponent bit `fp.y - 2 - (fp.x + s)` of `e_words` (`n - 1`, `fp.z`
/// words per instance) is set. After the squaring every limb is canonical (below 2^32), so no carry
/// ripple is needed: limb `c` of `2x` is `(x_c << 1) | (x_{c-1} >> 31)`, and a lane's limb 0 takes
/// its low bit from the previous lane's last limb (`up1`; 0 for lane 0). R > 16n gives `2x < 4n < R`,
/// so nothing leaves the top limb of the top lane. Every lane runs the shuffle (uniform control
/// flow); the bit only selects the result.
pub(crate) fn conditional_double(g: &mut Gen, lpl: usize) {
    g.line("let gi = fp.y - 2u - (fp.x + s);");
    g.line("let ebit = (e_words[ic * fp.z + (gi >> 5u)] >> (gi & 31u)) & 1u;");
    g.line(format!("var prev = up1(x{} >> 31u, lane);                 // bit shifted in from the lane below (0 for lane 0)", lpl - 1));
    for c in 0..lpl {
        g.line(format!("let d{c} = (x{c} << 1u) | prev;"));
        g.line(format!("prev = x{c} >> 31u;"));
    }
    for c in 0..lpl {
        g.line(format!("x{c} = select(x{c}, d{c}, ebit == 1u);"));
    }
}

/// One multiplier limb (`{mult}{w}` of lane `owner`, where `mult` is `x` when squaring and `b` when
/// multiplying): `t <- (t + x b + n m) / 2^32` over this lane's limbs.
///
/// Why the `wrap` branch of the last element is exact. Every chain input is a u32, so the carries
/// `c1`, `c2` are at most 2^32 - 1, and `a` and `q` (each a product of two u32 plus two u32 terms)
/// are at most (2^32-1)^2 + 2 (2^32-1) = 2^64 - 1: no u64 overflow inside the chains. The deferred
/// carry `pend` is below 2^34, so `s2 = q + pend` wraps at most once. A wrap loses 2^64, which is
/// 2^32 in units of the next limb (the limb above the element `s2` belongs to), and that is exactly
/// the `wrap` term (2^32) added to the new `pend`. After a wrap `s2 < pend < 2^34`, so
/// `s2 >> 32 < 4` and the new `pend = (s2 >> 32) + wrap + (a >> 32)` is below 4 + 2^32 + 2^32 =
/// 2^33 + 4; without a wrap it is below 2^32 + 2^32 = 2^33. Either way `pend` stays below 2^34, the
/// bound the next step relies on.
fn step(g: &mut Gen, lpl: usize, w: usize, mult: &str) {
    g.line("{");
    g.depth += 1;
    g.line(format!(
        "let bb = u64(bcast({mult}{w}, owner, base));       // multiplier limb"
    ));
    g.line("let T0 = bcast(t0, 0u, base);                   // accumulator limb 0 of lane 0");
    g.line("let TN = down1(t0, lane);                       // next lane's accumulator limb 0 (0 for the last lane)");
    g.line("let a0 = u64(T0) + u64(X0) * bb;                // lane 0's limb 0 after adding x*b");
    g.line("let m = u32(a0) * ninv;                         // Montgomery factor (u32 wrapping)");
    g.line("let mm = u64(m);");
    g.line("let b0 = u64(u32(a0)) + u64(N0) * mm;           // low word is zero");
    g.line("var c1 = select(0lu, a0 >> 32u, is0);           // carries of limb 0 enter lane 0's first element");
    g.line("var c2 = select(0lu, b0 >> 32u, is0);");
    for c in 0..lpl - 1 {
        let u = c + 1;
        g.line("{");
        g.depth += 1;
        g.line(format!("let a = u64(x{u}) * bb + u64(t{u}) + c1;"));
        g.line("c1 = a >> 32u;");
        g.line(format!("let q = u64(n{u}) * mm + u64(u32(a)) + c2;"));
        g.line(format!("t{c} = u32(q);"));
        g.line("c2 = q >> 32u;");
        g.depth -= 1;
        g.line("}");
    }
    let top = lpl - 1;
    g.line("{");
    g.depth += 1;
    g.line(
        "let a = u64(XN0) * bb + u64(TN) + c1;            // the next lane's limb 0, computed here",
    );
    g.line("let q = u64(NN0) * mm + u64(u32(a)) + c2;");
    g.line(
        "let s2 = q + pend;                               // pend below 2^34: wraps at most once",
    );
    g.line("let wrap = select(0lu, 4294967296lu, s2 < q);");
    g.line(format!("t{top} = u32(s2);"));
    g.line("pend = (s2 >> 32u) + wrap + (a >> 32u);         // below 2^33 + 4 (see the note on `step`)");
    g.depth -= 1;
    g.line("}");
    g.depth -= 1;
    g.line("}");
}

/// Adds every lane's pending carry into the next lane's limb 0 and ripples until none is left.
pub(crate) fn resolve(g: &mut Gen, lpl: usize) {
    g.line("for (var round = 0u; round < L + 2u; round++) {");
    g.depth += 1;
    g.line("let plo = u32(pend);");
    g.line("let phi = u32(pend >> 32u);");
    g.line("if (!any_nonzero(plo | phi)) { break; }");
    g.line("var carry = u64(up1(plo, lane)) + (u64(up1(phi, lane)) << 32u);");
    for c in 0..lpl {
        g.line(format!("let v{c} = u64(t{c}) + carry;"));
        g.line(format!("t{c} = u32(v{c});"));
        g.line(format!("carry = v{c} >> 32u;"));
    }
    g.line("pend = carry;");
    g.depth -= 1;
    g.line("}");
}
